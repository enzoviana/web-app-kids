// Fonctions de génération de code confidentiel
export const generateCodeConfidentiel = (): string => {
  const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
  let code = '';
  for (let i = 0; i < 6; i++) {
    code += chars.charAt(Math.floor(Math.random() * chars.length));
  }
  return code;
};

export const isCodeUnique = (code: string, enfants: Enfant[]): boolean => {
  return !enfants.some(e => e.codeConfidentiel === code);
};

